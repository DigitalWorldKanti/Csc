-- Run this once in Supabase Dashboard > SQL Editor.
create table if not exists public.visitor_registrations (
  id bigint generated by default as identity primary key,
  full_name text not null check (char_length(full_name) between 1 and 100),
  age smallint null check (age is null or age between 1 and 120),
  mobile text not null check (char_length(mobile) between 5 and 20),
  whatsapp text null check (whatsapp is null or char_length(whatsapp) <= 20),
  email text not null check (char_length(email) <= 254),
  ip_address inet null,
  created_at timestamptz not null default now()
);

alter table public.visitor_registrations enable row level security;

-- Public visitors may submit a registration. They cannot read registrations.
drop policy if exists "Allow public registration inserts" on public.visitor_registrations;
create policy "Allow public registration inserts"
on public.visitor_registrations
for insert
to anon, authenticated
with check (
  char_length(full_name) between 1 and 100
  and char_length(mobile) between 5 and 20
  and char_length(email) between 3 and 254
);

grant insert on public.visitor_registrations to anon, authenticated;
grant usage, select on sequence public.visitor_registrations_id_seq to anon, authenticated;
